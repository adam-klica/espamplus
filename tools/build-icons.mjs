// Writes the icon set to plugin/espam-core/includes/icons.php:
// Tabler outline icons (MIT) for UI/categories, Simple Icons (CC0) for Viber/WhatsApp.
//   node tools/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as si from 'simple-icons';

const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.resolve(here, '..', 'plugin', 'espam-core', 'includes', 'icons.php');
const tabler = [
  'device-laptop', 'device-tv', 'fridge', 'paperclip', 'printer', 'device-mobile', 'tool', 'packages',
  'arrow-up-right', 'arrow-right', 'phone', 'mail', 'clock', 'map-pin', 'id', 'building', 'message-circle',
  'x', 'menu-2', 'check', 'truck', 'search', 'file-invoice', 'send', 'building-store', 'shopping-cart',
  'tools-kitchen-2', 'briefcase', 'shield-check', 'adjustments-horizontal', 'stack-2', 'clipboard-list', 'world', 'home', 'chevron-right', 'certificate', 'clock-hour-4', 'route', 'package', 'users', 'rosette-discount-check', 'phone-call', 'checklist', 'receipt', 'circle-check', 'calendar-time', 'messages', 'list-details', 'repeat', 'bolt', 'quote',
];

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
let php = "<?php\n/**\n * Icons: Tabler outline (MIT, tabler.io) and Simple Icons (CC0). Generated by tools/build-icons.mjs — do not edit.\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nfunction espam_icon_data(): array {\n\treturn array(\n";
for (const name of tabler) {
  const file = path.join(here, 'node_modules/@tabler/icons/icons/outline', `${name}.svg`);
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '').replace(/\s+/g, ' ').trim();
  php += `\t\t'${name}' => array( 'line', '${esc(inner)}' ),\n`;
}
for (const name of ['siViber', 'siWhatsapp']) php += `\t\t'${name.slice(2).toLowerCase()}' => array( 'brand', '${si[name].path}' ),\n`;
php += '\t);\n}\n';
fs.writeFileSync(dest, php);
console.log('icons:', tabler.length + 2);

// Converts the site photos (photos/*.jpg + photos/credits.json) to WebP in two widths for the theme,
// and writes their alt text / size / licence to the plugin (includes/images.php).
//   node tools/build-images.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'photos');
const out = path.join(root, 'theme', 'espam', 'assets', 'img');
const php = path.join(root, 'plugin', 'espam-core', 'includes', 'images.php');
fs.mkdirSync(out, { recursive: true });

const credits = JSON.parse(fs.readFileSync(path.join(src, 'credits.json'), 'utf8'));
const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
let body = '';
for (const c of credits) {
  const name = c.file.replace(/\.jpe?g$/i, '');
  const input = path.join(src, c.file);
  const big = await sharp(input).resize({ width: 1600, withoutEnlargement: true }).webp({ quality: 74 }).toFile(path.join(out, `${name}.webp`));
  await sharp(input).resize({ width: 800, withoutEnlargement: true }).webp({ quality: 72 }).toFile(path.join(out, `${name}-800.webp`));
  body += `\t\t'${esc(name)}' => array( 'alt' => '${esc(c.alt)}', 'w' => ${big.width}, 'h' => ${big.height}, 'author' => '${esc(c.author)}', 'license' => '${esc(c.license)}', 'source' => '${esc(c.source)}' ),\n`;
}
fs.writeFileSync(
  php,
  "<?php\n/**\n * Site photos (theme/espam/assets/img/<name>.webp + <name>-800.webp) with alt text and licence.\n * Generated by tools/build-images.mjs — do not edit.\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nfunction espam_image_data(): array {\n\treturn array(\n" + body + '\t);\n}\n',
);
console.log('images:', credits.length);
